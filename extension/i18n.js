  let locale = DEFAULT_LOCALE;

  function normalizeLocale(value) {
    return LOCALES.has(value) ? value : DEFAULT_LOCALE;
  }

  function setLocale(value) {
    locale = normalizeLocale(value);
    return locale;
  }

  function getLocale() {
    return locale;
  }

  function t(key, vars = {}) {
    const template = messages[locale]?.[key] ?? messages[DEFAULT_LOCALE]?.[key] ?? key;
    return String(template).replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
  }

  function formatNumber(value) {
    return new Intl.NumberFormat(locale === "en" ? "en-US" : "zh-CN").format(Number(value) || 0);
  }

  function formatTime(value, { seconds = true } = {}) {
    if (!value) return "";
    try {
      return new Date(value).toLocaleTimeString(locale === "en" ? "en-US" : "zh-CN", {
        hour: "2-digit", minute: "2-digit", ...(seconds ? { second: "2-digit" } : {})
      });
    } catch { return ""; }
  }

  function formatDateTime(value) {
    if (!value) return "";
    try { return new Date(value).toLocaleString(locale === "en" ? "en-US" : "zh-CN"); } catch { return ""; }
  }

  async function loadLocale() {
    if (typeof chrome === "undefined" || !chrome.storage?.local?.get) return locale;
    try {
      const saved = await chrome.storage.local.get(["uiLanguage"]);
      return setLocale(saved.uiLanguage);
    } catch { return locale; }
  }

  globalThis.SolCodexI18n = {
    DEFAULT_LOCALE,
    normalizeLocale,
    setLocale,
    getLocale,
    loadLocale,
    t,
    formatNumber,
    formatTime,
    formatDateTime
  };
